create table if not exists public.izzy_rank_levels (
  code text primary key,
  name text not null,
  sort_order integer not null,
  is_career boolean not null default true,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint izzy_rank_levels_code_check check (code in ('novato', 'agente', 'supervisor', 'director', 'embajador'))
);

create table if not exists public.izzy_service_categories (
  code text primary key,
