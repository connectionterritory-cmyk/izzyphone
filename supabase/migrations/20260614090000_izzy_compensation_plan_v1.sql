update public.izzy_orders o
set
  portal_user_id = u.id,
  carrier_name = coalesce(nullif(o.carrier_name, ''), nullif(o.proveedor_servicio, '')),
  compensation_rank_code = coalesce(o.compensation_rank_code, u.compensation_role)
from public.izzy_portal_users u
where u.nombre = o.agente
  and (
    o.portal_user_id is null
    or o.carrier_name is null
    or o.compensation_rank_code is null
  );

update public.izzy_orders
set service_category_code = case
  when coalesce(velocidad_deseada, '') ilike '%2 gig%' then 'premium'
  when coalesce(velocidad_deseada, '') ilike '%1 gig%' then 'premium'
  when coalesce(velocidad_deseada, '') ilike '%fiber%' then 'premium'
  when coalesce(velocidad_deseada, '') ilike '%500%' then 'standard'
  when coalesce(velocidad_deseada, '') ilike '%300%' then 'standard'
  when coalesce(velocidad_deseada, '') ilike '%promo%' then 'basic'
  when coalesce(velocidad_deseada, '') ilike '%special%' then 'basic'
  else coalesce(service_category_code, 'standard')
end
where service_category_code is null;

update public.izzy_orders
set compensation_status = case
  when commission_status = 'paid' then 'paid'
  when commission_status = 'earned' then 'reserve'
  when commission_status = 'cancelled' then 'chargeback'
  else 'estimated'
end
where compensation_status is null
   or compensation_status = 'estimated';

